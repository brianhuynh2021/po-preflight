"use client";

import {
  createContext,
  useCallback,
  useContext,
  useEffect,
  useMemo,
  useState,
  type ReactNode,
} from "react";

import type { ActivityEvent, PurchaseOrder } from "@/app/lib/types";
import { seedOrders } from "@/app/lib/seed";

interface AppState {
  orders: PurchaseOrder[];
  setOrders: React.Dispatch<React.SetStateAction<PurchaseOrder[]>>;
  activity: ActivityEvent[];
  setActivity: React.Dispatch<React.SetStateAction<ActivityEvent[]>>;
  isLiveConnected: boolean;
  refreshOrders: () => Promise<void>;
}

const AppStateContext = createContext<AppState | null>(null);

const initialActivity: ActivityEvent[] = [
  {
    title: "Validation completed",
    detail: "2 findings generated by catalog and inventory rules",
    time: "10:43 AM",
    type: "system",
  },
  {
    title: "Order extracted",
    detail: "12 fields and 2 line items recognized",
    time: "10:42 AM",
    type: "system",
  },
  {
    title: "Order submitted",
    detail: "Uploaded by Olivia Park through the web portal",
    time: "10:42 AM",
    type: "human",
  },
];

export function AppStateProvider({ children }: { children: ReactNode }) {
  const [orders, setOrders] = useState<PurchaseOrder[]>(seedOrders);
  const [activity, setActivity] = useState<ActivityEvent[]>(initialActivity);
  const [isLiveConnected, setIsLiveConnected] = useState<boolean>(false);

  const refreshOrders = useCallback(async () => {
    try {
      const res = await fetch("http://localhost:8001/api/v1/orders");
      if (res.ok) {
        const liveData = await res.json();
        if (Array.isArray(liveData) && liveData.length > 0) {
          setIsLiveConnected(true);
        }
      }
    } catch {
      setIsLiveConnected(false);
    }
  }, []);

  useEffect(() => {
    // 1. Initial live check
    // eslint-disable-next-line react-hooks/set-state-in-effect
    void refreshOrders();

    // 2. Connect to real-time SSE stream if in browser
    if (typeof window !== "undefined" && "EventSource" in window) {
      try {
        const sse = new EventSource("http://localhost:8001/api/v1/events/stream");

        sse.onopen = () => {
          setIsLiveConnected(true);
        };

        sse.onmessage = (event) => {
          try {
            const payload = JSON.parse(event.data);
            if (payload.event === "order.created" || payload.event === "order.decided") {
              setActivity((prev) => [
                {
                  title: `Event: ${payload.event}`,
                  detail: `Order ${payload.data?.po_number || "updated"} status: ${payload.data?.status || "processed"}`,
                  time: "Just now",
                  type: "system",
                },
                ...prev,
              ]);
            }
          } catch {
            // Non-JSON ping message
          }
        };

        sse.onerror = () => {
          setIsLiveConnected(false);
        };

        return () => {
          sse.close();
        };
      } catch {
        // SSE not reachable in test environment
      }
    }
  }, [refreshOrders]);

  const value = useMemo(
    () => ({ orders, setOrders, activity, setActivity, isLiveConnected, refreshOrders }),
    [orders, activity, isLiveConnected, refreshOrders],
  );

  return (
    <AppStateContext.Provider value={value}>
      {children}
    </AppStateContext.Provider>
  );
}

export function useAppState(): AppState {
  const ctx = useContext(AppStateContext);
  if (!ctx) {
    throw new Error("useAppState must be used within an AppStateProvider");
  }
  return ctx;
}
